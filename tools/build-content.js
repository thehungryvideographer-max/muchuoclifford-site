#!/usr/bin/env node
/* ============================================================
   CONTENT BUILD
   Reads the files edited by Decap CMS (content/) and writes the
   data files the website uses (js/blog-data.js, js/gallery-data.js).
   Run locally:  node tools/build-content.js
   On Netlify this runs automatically before every deploy.
   ============================================================ */
const fs = require('fs');
const path = require('path');
const { marked } = require('./vendor/marked.cjs');

const ROOT = path.join(__dirname, '..');
const BLOG_DIR = path.join(ROOT, 'content', 'blog');
const GALLERY_FILE = path.join(ROOT, 'content', 'gallery.json');

const CAT_LABELS = {
  all: 'All',
  video: 'Video',
  events: 'Events',
  photo: 'Photography',
  design: 'Design',
  safety: 'Online Safety'
};

function slugify(text) {
  return String(text || 'project').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '') || 'project';
}

function buildBlog() {
  if (!fs.existsSync(BLOG_DIR)) {
    console.log('No content/blog folder, leaving blog data untouched.');
    return;
  }

  const posts = fs.readdirSync(BLOG_DIR)
    .filter(f => f.endsWith('.json'))
    .map(file => {
      const data = JSON.parse(fs.readFileSync(path.join(BLOG_DIR, file), 'utf8'));
      const slug = file.replace(/\.json$/i, '');
      const bodyHtml = data.body ? marked.parse(String(data.body)) : '';
      return {
        slug,
        type: data.type === 'vlog' ? 'vlog' : 'article',
        title: data.title || slug,
        date: data.date || '',
        read: data.read || '',
        tags: Array.isArray(data.tags) ? data.tags.filter(Boolean) : [],
        image: data.image || null,
        youtube: data.youtube || null,
        excerpt: data.excerpt || '',
        body: bodyHtml
      };
    })
    .sort((a, b) => new Date(b.date || 0) - new Date(a.date || 0));

  const output = `/* ============================================================
   GENERATED FILE, do not edit this file by hand.
   Write and edit posts in the CMS at /admin
   (they are stored in content/blog/*.json).
   Rebuild with: node tools/build-content.js
   ============================================================ */
const POSTS = ${JSON.stringify(posts, null, 2)};
`;

  fs.writeFileSync(path.join(ROOT, 'js', 'blog-data.js'), output);
  console.log(`blog: ${posts.length} post(s) written to js/blog-data.js`);
}

function buildGallery() {
  if (!fs.existsSync(GALLERY_FILE)) {
    console.log('No content/gallery.json, leaving gallery data untouched.');
    return;
  }

  const data = JSON.parse(fs.readFileSync(GALLERY_FILE, 'utf8'));
  const projects = (data.projects || []).map(p => ({
    id: slugify(p.title),
    title: p.title || '',
    cat: CAT_LABELS[p.cat] ? p.cat : 'video',
    client: p.client || '',
    badge: p.badge || '',
    desc: p.desc || '',
    img: p.img || '',
    videoUrl: p.videoUrl || null
  }));

  const output = `/* ============================================================
   GENERATED FILE, do not edit this file by hand.
   Add projects and pictures in the CMS at /admin
   (they are stored in content/gallery.json).
   Rebuild with: node tools/build-content.js
   ============================================================ */
const PROJECTS = ${JSON.stringify(projects, null, 2)};

const CAT_LABELS = ${JSON.stringify(CAT_LABELS, null, 2)};
`;

  fs.writeFileSync(path.join(ROOT, 'js', 'gallery-data.js'), output);
  console.log(`gallery: ${projects.length} project(s) written to js/gallery-data.js`);
}

buildBlog();
buildGallery();
